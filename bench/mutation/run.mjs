// codystem-to-10of10 — mutation-testing GATE. Runs the mutator over the pure-logic modules,
// aggregates a mutation score (killed / total), lists every SURVIVOR (a bug the tests miss), writes
// bench/mutation/report.md, and exits non-zero if the score is below MUT_THRESHOLD. Wire nightly / as
// a dedicated CI job (it re-runs each module's suite per mutant, so it is slower than verify.sh).
//
// Usage: pnpm run mutation      Env: MUT_THRESHOLD (default 0.90)

import { mutateFile } from "./mutate.mjs";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
// (src, test) pairs — pure modules whose test imports only that module + node builtins.
const TARGETS = [
  ["src/study.ts", "src/study.test.ts"],
  ["src/ops.ts", "src/ops.test.ts"],
  ["src/version.ts", "src/version.test.ts"],
  ["src/tenant.ts", "src/tenant.test.ts"],
  ["src/review-score.ts", "src/review-score.test.ts"],
  ["src/redteam-metrics.ts", "src/redteam-metrics.test.ts"],
];
// Ratchet FLOOR, not a target: it prevents test quality from silently regressing (delete tests →
// score drops → red). Set below the achieved score so a single flaky/timeout mutant can't red the
// gate; raise it over time as survivors are killed. Current achieved ≈ 97% (all residual survivors
// are proven-equivalent mutants — see docs/MUTATION.md), so the floor sits at 0.90.
const THRESHOLD = Number(process.env.MUT_THRESHOLD || 0.9);

const results = [];
for (const [src, test] of TARGETS) {
  process.stderr.write(`mutating ${src} … `);
  const r = mutateFile(join(ROOT, src), join(ROOT, test));
  process.stderr.write(r.baselinePass ? `${r.killed}/${r.total} killed\n` : `SKIP (baseline red)\n`);
  results.push({ src, ...r });
}

let total = 0;
let killed = 0;
const survivors = [];
const timeouts = [];
const sampledNote = [];
const skipped = [];
for (const r of results) {
  if (!r.baselinePass) {
    skipped.push(r.src);
    continue;
  }
  total += r.total;
  killed += r.killed;
  for (const s of r.survived) survivors.push({ file: r.src, ...s });
  for (const s of r.timedOut ?? []) timeouts.push({ file: r.src, ...s });
  if (r.sampledFrom) sampledNote.push(`${r.src} (${r.total}/${r.sampledFrom} sites)`);
}
// Timeouts are inconclusive, not kills: they are in `total` but never in `killed`, so they can only
// LOWER the score — a hang can never inflate it. Surfaced explicitly below.
const score = total ? Math.round((killed / total) * 1000) / 10 : 100;

const rows = results
  .filter((r) => r.baselinePass)
  .map((r) => `| ${r.src} | ${r.killed}/${r.total} | ${r.total ? Math.round((r.killed / r.total) * 100) : 100}% |`)
  .join("\n");
const survRows = survivors.length
  ? survivors.map((s) => `| ${s.file}:${s.line} | \`${s.orig}\` → \`${s.repl}\` |`).join("\n")
  : "| _none_ | — |";
const timeoutSection = timeouts.length
  ? `\n## Timed-out mutants (INCONCLUSIVE — a hang, not a caught bug; excluded from \`killed\`)\n| location | mutation |\n|---|---|\n${timeouts
      .map((s) => `| ${s.file}:${s.line} | \`${s.orig}\` → \`${s.repl}\` |`)
      .join("\n")}\n`
  : "";
const samplingNote = sampledNote.length
  ? `\n_⚠️ Sampled (site count exceeded the per-file cap): ${sampledNote.join(", ")} — score is over a subset._\n`
  : "";

const report = `# Mutation-testing report (test-quality gate)

Each mutant injects one small bug (via the TS AST) and re-runs that module's tests. A **survivor** is
a bug the tests would NOT catch — a concrete hole. Killed = the tests caught it. This measures whether
"verify.sh green" actually means "correct", the failure mode that slipped past green tests all session.

**Mutation score: ${killed}/${total} killed (${score}%)** — threshold ${THRESHOLD * 100}% → ${score >= THRESHOLD * 100 ? "PASS ✅" : "FAIL ❌"}
${skipped.length ? `\n_Skipped (baseline red — not mutation-testable as configured): ${skipped.join(", ")}_\n` : ""}
| module | killed/total | score |
|---|---|---|
${rows}

## Survivors (bugs the tests miss — add a test to kill each)
| location | mutation that survived |
|---|---|
${survRows}
${timeoutSection}${samplingNote}
_Every residual survivor above must be EITHER killed by a test OR justified as an equivalent mutant
(no observable behavior change, so no test can kill it) in \`docs/MUTATION.md\` — an unexplained
survivor is a test gap, not a footnote. Generated by \`pnpm run mutation\`._
`;
writeFileSync(join(ROOT, "bench", "mutation", "report.md"), report);
console.log(
  `mutation: ${killed}/${total} killed (${score}%), ${survivors.length} survivor(s), ${timeouts.length} timeout(s) → threshold ${THRESHOLD * 100}%`
);
for (const s of survivors) console.error(`  SURVIVOR ${s.file}:${s.line}  ${s.orig} → ${s.repl}`);
for (const s of timeouts) console.error(`  TIMEOUT  ${s.file}:${s.line}  ${s.orig} → ${s.repl}`);
process.exit(score >= THRESHOLD * 100 ? 0 : 1);
